// One-time parser: context/Programa_sintetico_fase_2.md → lib/nem/contenidos-fase2.ts
// Extracts the 34 official Contenidos + their 1°/2°/3° PDAs, VERBATIM.
// Run: node scripts/parse-contenidos.mjs   (re-run if the source md changes)
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'context/Programa_sintetico_fase_2.md'
const OUT = 'lib/nem/contenidos-fase2.ts'

const CAMPOS = [
  'Lenguajes',
  'Saberes y Pensamiento Científico',
  'Ética, Naturaleza y Sociedades',
  'De lo Humano y lo Comunitario',
]

const lines = readFileSync(SRC, 'utf8').split(/\r?\n/)
const out = []
let campo = null
let contenido = null
let grade = null // '1' | '2' | '3' | null

for (const raw of lines) {
  const line = raw.trim()
  const campoH = line.match(/^# (.+)$/)
  if (campoH && CAMPOS.includes(campoH[1])) {
    campo = campoH[1]
    contenido = null
    grade = null
    continue
  }
  const contH = line.match(/^### Contenido:\s*(.+)$/)
  if (contH) {
    contenido = { campo, contenido: contH[1].trim(), pdas1: [], pdas2: [], pdas3: [] }
    out.push(contenido)
    grade = null
    continue
  }
  const gradeH = line.match(/^\*\*([123])°\*\*$/)
  if (gradeH) {
    grade = gradeH[1]
    continue
  }
  // any other header ends the current grade collection
  if (line.startsWith('#') || line.startsWith('**')) {
    grade = null
    continue
  }
  if (grade && contenido && line.startsWith('- ')) {
    contenido[`pdas${grade}`].push(line.slice(2).trim())
  }
}

// self-check
const byCampo = {}
for (const c of out) byCampo[c.campo] = (byCampo[c.campo] ?? 0) + 1
if (out.length !== 34) throw new Error(`expected 34 contenidos, got ${out.length}`)
if (Object.keys(byCampo).length !== 4) throw new Error(`expected 4 campos, got ${Object.keys(byCampo)}`)
const empty = out.filter((c) => !c.pdas1.length || !c.pdas2.length || !c.pdas3.length)
if (empty.length)
  throw new Error(`contenidos missing a grade's PDAs: ${empty.map((c) => c.contenido).join(' | ')}`)

const header = `// AUTO-GENERATED by scripts/parse-contenidos.mjs — do NOT edit by hand.
// Verbatim official Contenidos + their 1°/2°/3° PDAs, NEM Fase 2 (Programa Sintético).
// Source: context/Programa_sintetico_fase_2.md

export type ContenidoPDA = {
  campo: string
  contenido: string
  pdas1: string[]
  pdas2: string[]
  pdas3: string[]
}

/** PDAs for a school grade label. Fase 2 = Kinder 1/2/3; anything else → 3° (default persona). */
export function pdasForGrade(row: ContenidoPDA, grade?: string | null): string[] {
  if (grade?.includes('1')) return row.pdas1
  if (grade?.includes('2')) return row.pdas2
  return row.pdas3
}

export const CONTENIDOS_FASE2_3: ContenidoPDA[] = `

writeFileSync(OUT, header + JSON.stringify(out, null, 2) + '\n')
console.log(`Wrote ${OUT}: ${out.length} contenidos`, byCampo)
