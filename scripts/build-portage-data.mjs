// Regenerates lib/nem/portage-data.ts from context/guia-portage.md.
// Run: node scripts/build-portage-data.mjs
// The markdown is a flattened checklist table; we keep only the preschool age
// bands (2-6) and drop the infant-stimulation appendix.
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'context/guia-portage.md'
const OUT = 'lib/nem/portage-data.ts'

// Area boundaries. The first area has no header in the source — the file opens
// straight into it after the "GUÍA PORTAGE" title.
const AREA_MARKERS = [
  { match: /^II\.\s*ÁREA DE DESARROLLO MOTRIZ/, name: 'Motriz' },
  { match: /^ÁREA DE LENGUAJE/, name: 'Lenguaje' },
  { match: /^ÁREA DE SOCIALIZACIÓN/, name: 'Socialización' },
  { match: /^ÁREA COGNITIVA/, name: 'Cognitiva' },
]
// Everything past this is newborn stimulation — irrelevant to preschool planning.
const STOP = /^CÓMO ESTIMULAR AL BEBE/

const KEEP_BANDS = new Set(['2-3', '3-4', '4-5', '5-6'])

const lines = readFileSync(SRC, 'utf8').split('\n')

/** @type {Record<string, Record<string, string[]>>} area -> band -> items */
const data = {}
let area = 'Autoayuda'
let band = null

for (const raw of lines) {
  const line = raw.replace(/\t.*$/, '').trim()
  if (!line) continue
  if (STOP.test(line)) break

  const marker = AREA_MARKERS.find((m) => m.match.test(line))
  if (marker) {
    area = marker.name
    band = null
    continue
  }

  const bandMatch = line.match(/^De (\d+) a (\d+) años?$/)
  if (bandMatch) {
    band = `${bandMatch[1]}-${bandMatch[2]}`
    continue
  }

  const item = line.match(/^\d+\.\s+(.+)$/)
  if (item && band && KEEP_BANDS.has(band)) {
    const text = item[1].replace(/\s+/g, ' ').trim()
    if (!text) continue
    data[area] ??= {}
    data[area][band] ??= []
    data[area][band].push(text)
  }
}

const areas = Object.keys(data)
const bands = [...KEEP_BANDS]

const body = bands
  .map((b) => {
    const perArea = areas
      .filter((a) => data[a]?.[b]?.length)
      .map((a) => {
        const items = data[a][b].map((t) => `      ${JSON.stringify(t)},`).join('\n')
        return `    ${JSON.stringify(a)}: [\n${items}\n    ],`
      })
      .join('\n')
    return `  ${JSON.stringify(b)}: {\n${perArea}\n  },`
  })
  .join('\n')

const out = `// AUTO-GENERATED by scripts/build-portage-data.mjs — do not edit by hand.
// Source: context/guia-portage.md (Guía Portage, developmental milestone checklist).
// Only preschool-relevant age bands (2-6) are kept.

/** Portage developmental areas. */
export type PortageArea = ${areas.map((a) => JSON.stringify(a)).join(' | ')}

/** Age bands in years, as they appear in the Portage guide. */
export type PortageBand = ${bands.map((b) => JSON.stringify(b)).join(' | ')}

export const PORTAGE_MILESTONES: Record<PortageBand, Partial<Record<PortageArea, string[]>>> = {
${body}
}
`

writeFileSync(OUT, out)
const total = bands.reduce(
  (n, b) => n + areas.reduce((m, a) => m + (data[a]?.[b]?.length ?? 0), 0),
  0
)
console.log(`Wrote ${OUT}: ${bands.length} bands, ${areas.length} areas, ${total} milestones`)
